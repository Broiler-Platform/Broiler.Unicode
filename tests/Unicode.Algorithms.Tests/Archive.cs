using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Broiler.Unicode.Algorithms;
using Broiler.Unicode.Generation;

namespace Broiler.Unicode.Algorithms.Tests;

/// <summary>
/// This repository's pinned Unicode archive, read off disk by the pin's own list, and the tables the
/// generator writes from it, computed once per test run.
/// </summary>
internal static class Archive
{
    /// <summary>The pin, relative to the repository root.</summary>
    internal const string PinPath = "data/unicode/pins/unicode.pin";

    /// <summary>Broiler.VM's pin as this repository keeps a copy of it.</summary>
    internal const string BroilerVmPinPath = "data/unicode/pins/broiler-vm/unicode.pin";

    /// <summary>The generated tables' C# source, relative to the repository root.</summary>
    internal const string TableSourcePath = "src/Unicode.Tables/UnicodeTableData.g.cs";

    /// <summary>Set to <c>1</c> to make the regeneration test write rather than assert.</summary>
    internal const string WriteVariable = "BROILER_UNICODE_WRITE";

    private static readonly Lazy<string> root = new(static () =>
    {
        for (var directory = new DirectoryInfo(AppContext.BaseDirectory); directory is not null; directory = directory.Parent)
        {
            if (File.Exists(Path.Combine(directory.FullName, "Broiler.Unicode.slnx")))
            {
                return directory.FullName;
            }
        }

        throw new InvalidOperationException("No Broiler.Unicode.slnx above the test's directory.");
    });

    private static readonly Lazy<UnicodePin> pin = new(static () => UnicodePin.Parse(File.ReadAllText(Full(PinPath))));

    private static readonly Lazy<IReadOnlyDictionary<string, byte[]>> files = new(static () => Read(Pin));

    private static readonly Lazy<IReadOnlyList<KeyValuePair<UnicodeTable, byte[]>>> tables =
        new(static () => UnicodeTableGenerator.Generate(Pin, Files));

    /// <summary>The repository root.</summary>
    internal static string Root => root.Value;

    /// <summary>The pin on disk.</summary>
    internal static UnicodePin Pin => pin.Value;

    /// <summary>Every pinned file's bytes, by the name the pin writes it under.</summary>
    internal static IReadOnlyDictionary<string, byte[]> Files => files.Value;

    /// <summary>The generated tables.</summary>
    internal static IReadOnlyList<KeyValuePair<UnicodeTable, byte[]>> Tables => tables.Value;

    /// <summary>The comment lines the generated C# file opens with.</summary>
    internal static readonly string[] SourceHeader =
    [
        "GENERATED by Broiler.Unicode.Generation from the Unicode Character Database 17.0.0 files, the",
        "auxiliary break data, the emoji sequence files and the ECMAScript property tables that",
        "data/unicode/pins/unicode.pin names. The test project regenerates this file and compares it byte for",
        "byte (the shared JavaScript libraries programme's rule SL7), so a change belongs in the generator or",
        "the pin and never here: run the tests with BROILER_UNICODE_WRITE=1.",
        string.Empty,
        "The table data is derived from Unicode data files and is subject to the Unicode License v3 (SPDX",
        "Unicode-3.0), whose text THIRD_PARTY_NOTICES.md carries.",
    ];

    /// <summary>The C# source the generator writes for the Tables package.</summary>
    internal static string TableSource(IReadOnlyList<KeyValuePair<UnicodeTable, byte[]>> generated) =>
        UnicodeTableSource.Write(generated, "Broiler.Unicode.Tables", "UnicodeTableData", SourceHeader);

    /// <summary>A path relative to the repository root, made absolute.</summary>
    internal static string Full(string relativePath) =>
        Path.Combine(Root, relativePath.Replace('/', Path.DirectorySeparatorChar));

    /// <summary>The text of a pinned file.</summary>
    internal static string Text(string name) => UnicodePin.Decode(Files[name]);

    /// <summary>Reads every file a pin names off disk: a <c>file</c> beside the pin, a <c>spec-table</c> from the root.</summary>
    internal static IReadOnlyDictionary<string, byte[]> Read(UnicodePin source)
    {
        var directory = Path.GetDirectoryName(Full(PinPath))!;

        return source.Entries.ToDictionary(
            static entry => entry.Name,
            entry => File.ReadAllBytes(entry.Kind == "file"
                ? Path.Combine(directory, entry.Name.Replace('/', Path.DirectorySeparatorChar))
                : Full(entry.Name)),
            StringComparer.Ordinal);
    }
}
